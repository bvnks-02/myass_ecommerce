-- ---------------------------------------------------------------------------
-- 4. messages + RPC + realtime
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  sender_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  content TEXT NOT NULL CHECK (char_length(content) BETWEEN 1 AND 4000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  read_at TIMESTAMPTZ
);

ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Read own conversation or admin reads all" ON public.messages;
CREATE POLICY "Read own conversation or admin reads all" ON public.messages
  FOR SELECT TO authenticated
  USING (conversation_id = (select auth.uid()) OR public.is_admin());

DROP POLICY IF EXISTS "Send message" ON public.messages;
CREATE POLICY "Send message" ON public.messages
  FOR INSERT TO authenticated
  WITH CHECK (
    sender_id = (select auth.uid())
    AND (
      conversation_id = (select auth.uid())
      OR public.is_admin()
    )
  );

CREATE INDEX IF NOT EXISTS idx_messages_conversation_created
  ON public.messages (conversation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_unread
  ON public.messages (conversation_id) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_messages_sender ON public.messages (sender_id);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime'
      AND schemaname = 'public'
      AND tablename = 'messages'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.mark_messages_read(p_conversation UUID)
RETURNS VOID AS $$
BEGIN
  IF (select auth.uid()) IS NULL THEN
    RAISE EXCEPTION 'not authenticated';
  END IF;
  IF NOT (p_conversation = (select auth.uid()) OR public.is_admin()) THEN
    RAISE EXCEPTION 'not authorized';
  END IF;
  UPDATE public.messages
     SET read_at = NOW()
   WHERE conversation_id = p_conversation
     AND sender_id <> (select auth.uid())
     AND read_at IS NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE EXECUTE ON FUNCTION public.mark_messages_read(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.mark_messages_read(UUID) TO authenticated;

